"""Does the count graph clear the marginal on FB15k-237?

`fb15k237_audit.py` established what the benchmark hands over free: ranking
entities by how often they are a relation's tail — with no reference at all to
the entity being asked about — scores MRR 0.2334, against published DistMult at
0.241 and ComplEx at 0.247. **So the number that means anything here is the
margin over that floor, and this run reports the margin.**

## The arms are one mechanism with halves switched off

`composition.Composition` counts a triple as three role-marked surfaces and
scores a candidate from whichever roles the query supplies. That makes the floor
and the mechanism the same program:

    relation only     the floor. Rank tails by the relation alone
    entity only       what the head entity alone says, ignoring the relation
    both              the mechanism, combining them

A separately written baseline could drift from the arm it is the floor for.
This one cannot: it is the same call with one fewer key in the dict.

Both directions are scored — `(head, relation, ?)` and `(?, relation, tail)` —
off the same counts, because the surfaces are role-marked and the graph's
direction is in the roles rather than in a second table. RotatE's evaluation
section (ICLR 2019) is the protocol: filtered against train, validation and test,
candidates generated by corrupting subjects or objects.

**And every arm is reported under all three tie policies**, because a counting
score puts thousands of entities on exactly zero and the policy moves the number
a long way — while the published models it is compared against have continuous
scores and almost no ties.

    python experiments/fb15k237_counted.py --json out/fb15k237-counted.json
    python experiments/fb15k237_counted.py --queries 2000
"""

from __future__ import annotations

import argparse
import json
import pathlib
import random
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from experiments.fb15k237_audit import (PUBLISHED, Ranker,  # noqa: E402
                                        load, metrics, plain_rank)
from openplexus.composition import Composition  # noqa: E402
from openplexus.grounding import STATISTICS  # noqa: E402

#: Statistics to sweep. `conditional` is the one measured to refuse an
#: ever-present distractor (g39-04) and `local` is the purely-local arm C1 wants
#: to be true; both are swept here rather than one being pinned quietly.
STATISTICS_SWEPT = ("conditional", "ppmi", "local")

#: Combiners for the two halves. Swept for the same reason: `min` demands both
#: halves back a candidate and `mean` lets one carry it, and which is right is
#: not known here.
COMBINERS_SWEPT = ("min", "mean")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=pathlib.Path, default=None)
    parser.add_argument("--queries", type=int, default=None,
                        help="score this many test triples instead of all")
    # Chosen here, and it only picks the query subsample; the full run uses
    # every test triple and the seed does not enter the reported numbers.
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    started = time.time()
    train, valid, test = load("train.txt"), load("valid.txt"), load("test.txt")
    entities = sorted({e for triples in (train, valid, test)
                       for h, _, t in triples for e in (h, t)})
    relations = sorted({r for _, r, _ in train})
    entity_at = {name: i for i, name in enumerate(entities)}
    relation_at = {name: i for i, name in enumerate(relations)}
    print(f"train {len(train)}  test {len(test)}  entities {len(entities)}  "
          f"relations {len(relations)}")

    counts = Composition(len(entities), right=len(relations),
                         target=len(entities))
    for head, relation, tail in train:
        counts.observe(entity_at[head], relation_at[relation], entity_at[tail])
    print(f"counted {len(train)} triples into {counts.width} surfaces "
          f"({time.time() - started:.1f}s)")

    known_tails: dict = {}
    known_heads: dict = {}
    for head, relation, tail in train + valid + test:
        known_tails.setdefault((head, relation), set()).add(tail)
        known_heads.setdefault((relation, tail), set()).add(head)
    ranker = Ranker(entities, known_tails, known_heads)

    queries = test if args.queries is None else random.Random(
        args.seed).sample(test, min(args.queries, len(test)))
    print(f"scoring {len(queries)} triples in both directions\n")

    def scores_for(arm: str, head: str, relation: str, tail: str,
                   direction: str, statistic, combine: str) -> np.ndarray:
        """One arm's score over every candidate, as a dense vector.

        The ranking machinery is the audit's, so the two runs cannot be scored
        by two different rulers -- which is the failure this project files under
        *one implementation per behaviour*.
        """
        want = "target" if direction == "tail" else "left"
        supplied = {"right": relation_at[relation]}
        if arm != "relation only":
            supplied[("left" if direction == "tail" else "target")] = (
                entity_at[head if direction == "tail" else tail])
        if arm == "entity only":
            supplied.pop("right")
        vector = np.zeros(len(entities))
        for score, candidate in counts.given(supplied, want, statistic,
                                             combine):
            vector[candidate] = score
        return vector

    rows: list[dict] = []
    checked = False
    for statistic_name in STATISTICS_SWEPT:
        statistic = STATISTICS[statistic_name]
        for combine in COMBINERS_SWEPT:
            for arm in ("relation only", "entity only", "both"):
                # The one-sided arms do not use a combiner, so running them
                # once per combiner would report one number twice and invite it
                # being read as agreement between two measurements.
                if arm != "both" and combine != COMBINERS_SWEPT[0]:
                    continue
                middles, best, worst = [], [], []
                for head, relation, tail in queries:
                    for direction in ("tail", "head"):
                        given, answer = ((head, tail) if direction == "tail"
                                         else (tail, head))
                        vector = scores_for(arm, head, relation, tail,
                                            direction, statistic, combine)
                        top, middle, bottom = ranker.rank(
                            vector, given, relation, answer, direction)
                        if not checked:
                            # THE RULER AGAINST ITSELF, once, before any number
                            # below is read.
                            slow = plain_rank(vector, ranker.at, given,
                                              relation, answer, known_tails,
                                              known_heads, direction)
                            if slow != (top, middle, bottom):
                                raise SystemExit(
                                    f"rankers disagree: {slow} against "
                                    f"{(top, middle, bottom)}")
                            checked = True
                        middles.append(middle)
                        best.append(top)
                        worst.append(bottom)
                got = metrics(middles) | {
                    "arm": arm, "statistic": statistic_name,
                    "combine": combine if arm == "both" else None,
                    "mrr_optimistic": metrics(best)["mrr"],
                    "mrr_pessimistic": metrics(worst)["mrr"]}
                rows.append(got)
                label = (f"{arm} / {statistic_name}"
                         + (f" / {combine}" if arm == "both" else ""))
                print(f"{label:<34}  MRR {got['mrr']:.4f}  "
                      f"hits@1 {got['hits1']:.4f}  hits@10 {got['hits10']:.4f}"
                      f"   ties {got['mrr_pessimistic']:.4f}-"
                      f"{got['mrr_optimistic']:.4f}")

    # WHY THE ENTITY HALF CONTRIBUTES NOTHING, measured rather than guessed.
    # A one-step count can only speak about things that co-occurred, and a
    # link-prediction query asks for an edge that is not in training -- so the
    # answer is never one step away. This says how far away it is instead.
    adjacent: dict = {}
    for head, _, tail in train:
        adjacent.setdefault(head, set()).add(tail)
        adjacent.setdefault(tail, set()).add(head)
    sample = random.Random(args.seed).sample(queries, min(3000, len(queries)))
    hops = {1: 0, 2: 0, 3: 0, 0: 0}
    for head, _, tail in sample:
        near = adjacent.get(head, set())
        if tail in near:
            hops[1] += 1
            continue
        two = set().union(*(adjacent.get(x, set()) for x in near)) if near else set()
        if tail in two:
            hops[2] += 1
            continue
        three = set().union(*(adjacent.get(x, set()) for x in two)) if two else set()
        hops[3 if tail in three else 0] += 1
    print(f"\nHow far apart the endpoints of a test triple are in TRAIN, "
          f"over {len(sample)}:")
    for distance in (1, 2, 3):
        print(f"  {distance} hop{'s' if distance > 1 else ' '}  "
              f"{hops[distance] / len(sample):.4f}")
    print(f"  further or not at all  {hops[0] / len(sample):.4f}")

    # AND HOW MUCH OF THAT TWO-HOP CONNECTIVITY IS ONLY HUBS. The figure above
    # is measured with no cap, and a typed walk caps its fan-out -- so a pair
    # joined only through an entity carrying thousands of edges is counted as
    # reachable here and is missed in practice. If most two-hop connections are
    # hub-mediated then the gap between 0.7373 and the walk's 35% is not
    # headroom, it is an artefact of measuring connectivity without the budget
    # that any real walk has to spend.
    degree = {entity: len(near) for entity, near in adjacent.items()}
    bands = ((10, "under 10"), (100, "10 to 99"), (1000, "100 to 999"),
             (10 ** 9, "1000 or more"))
    smallest: dict = {label: 0 for _, label in bands}
    joined = 0
    for head, _, tail in sample:
        via = [x for x in adjacent.get(head, ()) if tail in adjacent.get(x, ())]
        if not via:
            continue
        joined += 1
        least = min(degree[x] for x in via)
        for limit, label in bands:
            if least < limit:
                smallest[label] += 1
                break
    print(f"\nOf the {joined} pairs joined in two hops, the degree of the "
          f"SMALLEST intermediate that joins them:")
    for _, label in bands:
        print(f"  {label:<14} {smallest[label] / max(joined, 1):.4f}")
    print("  A pair whose only intermediates are hubs is reachable on paper "
          "and not by any walk with a budget.")
    rows.append({"arm": "intermediates", "joined": joined,
                 **{label: smallest[label] / max(joined, 1)
                    for _, label in bands}})
    print("  A one-step mechanism cannot reach an answer that is two steps "
          "away, whatever statistic it uses.")
    rows.append({"arm": "reachability",
                 **{f"hops_{k}": v / len(sample) for k, v in hops.items()}})

    floors = [row for row in rows if row["arm"] == "relation only"]
    floor = max(row["mrr"] for row in floors)
    best_row = max((row for row in rows if row["arm"] == "both"),
                   key=lambda row: row["mrr"])
    print(f"\nThe floor, by this mechanism's own relation-only arm: "
          f"{floor:.4f}")
    print(f"The best combined arm: {best_row['mrr']:.4f} "
          f"({best_row['statistic']} / {best_row['combine']})")
    print(f"MARGIN OVER THE FLOOR: {best_row['mrr'] - floor:+.4f}")
    print("\nPublished, for the margin each of them holds over the same floor:")
    for name, (mrr, _) in sorted(PUBLISHED.items(), key=lambda item: item[1][0]):
        print(f"  {name:>10}  {mrr:.4f}   margin {mrr - floor:+.4f}")

    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(rows, indent=1), encoding="utf-8")
        print(f"\n{len(rows)} rows -> {args.json}")
    print(f"COST: {time.time() - started:.1f}s wall, one process")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
